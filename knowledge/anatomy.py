def types_of(codes) -> set[str]:
    return {BY_CODE[code].type for code in codes if code in BY_CODE}


def ancestors(code: str) -> list[Structure]:
    chain: list[Structure] = []
    seen = {code}
    current = BY_CODE.get(code)
    while current is not None and current.parent and current.parent not in seen:
        parent = BY_CODE.get(current.parent)
        if parent is None:
            break
        chain.append(parent)
        seen.add(parent.code)
        current = parent
    return chain


def breadcrumb(code: str) -> list[tuple[str, str]]:
    structure = BY_CODE.get(code)
    if structure is None:
        return []
    region_label = dict(REGIONS).get(structure.region, structure.region)
    trail = [(structure.region, region_label)]
    for ancestor in reversed(ancestors(code)):
        trail.append((ancestor.code, ancestor.label))
    trail.append((structure.code, structure.label))
    return trail


def subregion_of(code: str) -> str | None:
    structure = BY_CODE.get(code)
    if structure is None:
        return None
    if structure.subregion:
        return structure.subregion
    for ancestor in ancestors(code):
        if ancestor.subregion:
            return ancestor.subregion
        if ancestor.type == REGION:
            return ancestor.label
    return None


def related(code: str) -> list[tuple[str, str]]:
    return list(_RELATED.get(code, ()))


def children(code: str) -> tuple[Structure, ...]:
    return tuple(structure for structure in STRUCTURES if structure.parent == code)


def _search_terms(structure: Structure) -> tuple[str, ...]:
    return tuple(
        term.lower()
        for term in (structure.label, structure.latin, *structure.synonyms, structure.code)
        if term
    )


_TERMS = {structure.code: _search_terms(structure) for structure in STRUCTURES}

_SIDE_WORDS = frozenset({"left", "right", "bilateral"})


def search(query: str, limit: int = 25, sex: str | None = None) -> list[Structure]:
    words = query.lower().split()
    if len(words) > 1 and words[0] in _SIDE_WORDS:
        words = words[1:]
    needle = " ".join(words)
    if not needle:
        return []
    scored: list[tuple[tuple[int, int, str], Structure]] = []
    for structure in STRUCTURES:
        if sex in ("F", "M") and structure.sex not in (None, sex):
            continue
        terms = _TERMS[structure.code]
        best = None
        for index, term in enumerate(terms):
            if term == needle:
                rank = 0
            elif term.startswith(needle):
                rank = 1
            elif any(word.startswith(needle) for word in term.split()):
                rank = 2
            elif needle in term:
                rank = 3
            else:
                continue
            candidate = (rank, min(index, 2) + (1 if structure.type == REGION else 0))
            if best is None or candidate < best:
                best = candidate
        if best is not None:
            scored.append(((*best, structure.label), structure))
    scored.sort(key=lambda item: item[0])
    return [structure for _, structure in scored[:limit]]


def of_type(type_code: str) -> tuple[Structure, ...]:
    return tuple(structure for structure in STRUCTURES if structure.type == type_code)


def in_region(region: str) -> tuple[Structure, ...]:
    return tuple(structure for structure in STRUCTURES if structure.region == region)


def projected_locations(code: str, side: str) -> tuple[tuple[str, str], ...]:
    structure = BY_CODE.get(code)
    if structure is None:
        return ()
    if side == "BILATERAL" and (structure.location_left or structure.location_right):
        return (
            (structure.location_for("LEFT"), "LEFT"),
            (structure.location_for("RIGHT"), "RIGHT"),
        )
    return ((structure.location_for(side), side),)


def combine_sides(first: str, second: str) -> str:
    if first == second:
        return first
    vague = {"MIDLINE", "NOT_APPLICABLE"}
    if first in vague:
        return second
    if second in vague:
        return first
    return "BILATERAL"


def _location_laterality() -> dict[str, str]:
    mapping: dict[str, str] = {}
    for zone in of_type(REGION):
        mapping.setdefault(zone.location, zone.laterality)
        if zone.location_left:
            mapping.setdefault(zone.location_left, LEFT)
        if zone.location_right:
            mapping.setdefault(zone.location_right, RIGHT)
    return mapping


LOCATION_LATERALITY = _location_laterality()


def tree() -> list[dict]:
    grouped: list[dict] = []
    for region_code, region_label in REGIONS:
        members = in_region(region_code)
        if not members:
            continue
        groups = []
        for entry in STRUCTURE_TYPES:
            of_this_type = [s for s in members if s.type == entry.code]
            if of_this_type:
                groups.append(
                    {
                        "type": entry.code,
                        "label": entry.label,
                        "structures": [s.code for s in of_this_type],
                    }
                )
        grouped.append({"region": region_code, "label": region_label, "types": groups})
    return grouped


def counts() -> dict[str, int]:
    out = {entry.code: 0 for entry in STRUCTURE_TYPES}
    for structure in STRUCTURES:
        out[structure.type] += 1
    out["total"] = len(STRUCTURES)
    out["relationships"] = len(RELATIONSHIPS)
    return out
