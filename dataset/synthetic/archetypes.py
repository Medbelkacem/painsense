from dataclasses import dataclass

Weighted = tuple[tuple[str, float], ...]

NEUROPATHIC_RADIATION = ("SHOOTING", "ELECTRIC", "BURNING", "TINGLING")

IMPROVING = "IMPROVING"
WORSENING = "WORSENING"
STABLE = "STABLE"
FLARE = "FLARE"
TRAJECTORIES = (IMPROVING, WORSENING, STABLE, FLARE)

ACUTE_TRAJECTORIES: Weighted = ((IMPROVING, 0.55), (STABLE, 0.25), (WORSENING, 0.2))
CHRONIC_TRAJECTORIES: Weighted = (
    (STABLE, 0.45),
    (FLARE, 0.3),
    (WORSENING, 0.15),
    (IMPROVING, 0.1),
)
EPISODIC_TRAJECTORIES: Weighted = ((FLARE, 0.5), (STABLE, 0.3), (IMPROVING, 0.2))


@dataclass(frozen=True)
class Archetype:
    code: str
    label: str
    weight: float
    age_range: tuple[int, int]
    female_probability: float
    primary_sites: Weighted
    qualities: tuple[str, ...]
    quality_count: tuple[int, int]
    base_pain: float
    pain_spread: float
    duration_hours: tuple[float, float]
    onset_speed: Weighted
    pattern: Weighted
    course: Weighted
    trajectories: Weighted

    onset: Weighted = (("GRADUAL", 0.6), ("SUDDEN", 0.4))
    secondary_sites: Weighted = ()
    radiation_chains: tuple[tuple[str, ...], ...] = ()
    radiation_probability: float = 0.0
    radiating_qualities: tuple[str, ...] = NEUROPATHIC_RADIATION
    referred_sites: Weighted = ()
    timing: Weighted = ()
    symptoms: Weighted = ()
    factors: Weighted = ()
    conditions: Weighted = ()
    confounders: Weighted = ()
    medications: Weighted = ()
    answers: tuple[tuple[str, object, float], ...] = ()
    recurrent_probability: float = 0.1
    recent_trauma_probability: float = 0.0
    recent_surgery_probability: float = 0.0

    affects_saturation: bool = False
    febrile_tendency: float = 0.0

    bilateral_probability: float = 0.16

    @property
    def chronic(self) -> bool:
        return self.duration_hours[1] >= 2000.0


