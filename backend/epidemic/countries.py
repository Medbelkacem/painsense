ISO3_TO_NAME = {iso3: name for iso3, name in ISO2_TO_ISO3.values()}


def to_iso3(code: object) -> str | None:
    """Translate an alpha-2 code, tolerating an alpha-3 that is already correct."""
    if not isinstance(code, str):
        return None
    key = code.strip().upper()
    if len(key) == 3:
        return key if key in ISO3_TO_NAME else None
    pair = ISO2_TO_ISO3.get(key)
    return pair[0] if pair else None


def name_for(iso3: object) -> str | None:
    return ISO3_TO_NAME.get(iso3) if isinstance(iso3, str) else None
